package crypto

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"errors"
	"fmt"
	"io"
)

var (
	MagicHeader = []byte("TGC1") // TeleClone Crypt Version 1
	ErrInvalidHeader = errors.New("invalid encryption magic header")
	ErrDecryptionFailed = errors.New("decryption failed: incorrect password or corrupted data")
)

const (
	SaltSize    = 16
	NonceSize   = 12
	KeySize     = 32 // AES-256
	PBKDF2Iters = 60000
)

// DeriveKey derives a 32-byte AES-256 key from a passphrase and salt using PBKDF2-HMAC-SHA256
func DeriveKey(passphrase string, salt []byte) []byte {
	return pbkdf2SHA256([]byte(passphrase), salt, PBKDF2Iters, KeySize)
}

// pbkdf2SHA256 implements RFC 2898 PBKDF2 using HMAC-SHA256 with pure Go standard library
func pbkdf2SHA256(password, salt []byte, iter, keyLen int) []byte {
	prf := hmac.New(sha256.New, password)
	hashLen := prf.Size()
	numBlocks := (keyLen + hashLen - 1) / hashLen

	var buf [4]byte
	dk := make([]byte, 0, numBlocks*hashLen)
	u := make([]byte, hashLen)
	ti := make([]byte, hashLen)

	for block := 1; block <= numBlocks; block++ {
		// U_1 = PRF(password, salt || INT_32_BE(block))
		prf.Reset()
		prf.Write(salt)
		binary.BigEndian.PutUint32(buf[:], uint32(block))
		prf.Write(buf[:])
		u = prf.Sum(u[:0])
		copy(ti, u)

		// U_2 .. U_c
		for i := 2; i <= iter; i++ {
			prf.Reset()
			prf.Write(u)
			u = prf.Sum(u[:0])
			for k := 0; k < hashLen; k++ {
				ti[k] ^= u[k]
			}
		}
		dk = append(dk, ti...)
	}

	return dk[:keyLen]
}

// EncryptChunk encrypts raw data with AES-256-GCM and generates a self-contained container
// Format: [4B Magic TGC1][16B Salt][12B Nonce][Ciphertext + 16B GCM Tag]
func EncryptChunk(plaintext []byte, passphrase string) ([]byte, error) {
	salt := make([]byte, SaltSize)
	if _, err := io.ReadFull(rand.Reader, salt); err != nil {
		return nil, fmt.Errorf("generate salt: %w", err)
	}

	key := DeriveKey(passphrase, salt)
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("create cipher: %w", err)
	}

	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("create gcm: %w", err)
	}

	nonce := make([]byte, NonceSize)
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return nil, fmt.Errorf("generate nonce: %w", err)
	}

	// Seal plaintext into ciphertext with appended auth tag
	ciphertext := gcm.Seal(nil, nonce, plaintext, MagicHeader)

	// Build output buffer
	out := make([]byte, 0, len(MagicHeader)+SaltSize+NonceSize+len(ciphertext))
	out = append(out, MagicHeader...)
	out = append(out, salt...)
	out = append(out, nonce...)
	out = append(out, ciphertext...)

	return out, nil
}

// DecryptChunk authenticates and decrypts a chunk generated by EncryptChunk
func DecryptChunk(data []byte, passphrase string) ([]byte, error) {
	minSize := len(MagicHeader) + SaltSize + NonceSize + 16 // 16 is GCM tag size
	if len(data) < minSize {
		return nil, ErrDecryptionFailed
	}

	if !bytes.Equal(data[:len(MagicHeader)], MagicHeader) {
		return nil, ErrInvalidHeader
	}

	offset := len(MagicHeader)
	salt := data[offset : offset+SaltSize]
	offset += SaltSize

	nonce := data[offset : offset+NonceSize]
	offset += NonceSize

	ciphertext := data[offset:]

	key := DeriveKey(passphrase, salt)
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("create cipher: %w", err)
	}

	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("create gcm: %w", err)
	}

	plaintext, err := gcm.Open(nil, nonce, ciphertext, MagicHeader)
	if err != nil {
		return nil, ErrDecryptionFailed
	}

	return plaintext, nil
}

// HashData calculates SHA-256 hex string of data
func HashData(data []byte) string {
	h := sha256.Sum256(data)
	return fmt.Sprintf("%x", h[:])
}

// HashStream calculates SHA-256 of an io.Reader
func HashStream(r io.Reader) (string, int64, error) {
	h := sha256.New()
	n, err := io.Copy(h, r)
	if err != nil {
		return "", 0, err
	}
	return fmt.Sprintf("%x", h.Sum(nil)), n, nil
}
